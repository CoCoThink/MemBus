"""SQLite persistence for MemBus."""

from __future__ import annotations

import sqlite3
from collections.abc import Iterable
from typing import Any

from .db import Database
from .models import Memory


_MEMORY_COLUMNS = (
    "id",
    "title",
    "content",
    "memory_type",
    "scope",
    "workspace",
    "project",
    "repo",
    "branch",
    "source_type",
    "source_ref",
    "created_at",
    "updated_at",
    "deleted_at",
)


class MemoryRepository:
    def __init__(self, db: Database) -> None:
        self.db = db

    def create(self, memory: Memory) -> None:
        with self.db.transaction() as conn:
            conn.execute(
                """
                INSERT INTO memories (
                    id, title, content, memory_type, scope,
                    workspace, project, repo, branch,
                    source_type, source_ref,
                    created_at, updated_at, deleted_at
                ) VALUES (
                    :id, :title, :content, :memory_type, :scope,
                    :workspace, :project, :repo, :branch,
                    :source_type, :source_ref,
                    :created_at, :updated_at, :deleted_at
                )
                """,
                _memory_params(memory),
            )

    def get(self, memory_id: str, *, include_deleted: bool = False) -> Memory | None:
        sql = "SELECT * FROM memories WHERE id = ?"
        params: list[Any] = [memory_id]
        if not include_deleted:
            sql += " AND deleted_at IS NULL"

        with self.db.connection() as conn:
            row = conn.execute(sql, params).fetchone()
        return _memory_from_row(row) if row is not None else None

    def update(self, memory: Memory) -> Memory:
        with self.db.transaction() as conn:
            cursor = conn.execute(
                """
                UPDATE memories
                SET
                    title = :title,
                    content = :content,
                    memory_type = :memory_type,
                    scope = :scope,
                    workspace = :workspace,
                    project = :project,
                    repo = :repo,
                    branch = :branch,
                    source_type = :source_type,
                    source_ref = :source_ref,
                    updated_at = :updated_at,
                    deleted_at = :deleted_at
                WHERE id = :id
                """,
                _memory_params(memory),
            )
            if cursor.rowcount == 0:
                raise KeyError(memory.id)
        return memory

    def logical_delete(self, memory_id: str, *, deleted_at: str) -> bool:
        with self.db.transaction() as conn:
            cursor = conn.execute(
                """
                UPDATE memories
                SET deleted_at = ?,
                    updated_at = ?
                WHERE id = ?
                  AND deleted_at IS NULL
                """,
                (deleted_at, deleted_at, memory_id),
            )
            return cursor.rowcount > 0

    def exact_candidates(
        self,
        query: str,
        *,
        types: tuple[str, ...] = (),
        limit: int = 50,
    ) -> list[Memory]:
        where = [
            """
            (
                instr(lower(m.title), lower(?)) > 0
                OR instr(lower(m.content), lower(?)) > 0
            )
            """,
            "m.deleted_at IS NULL",
        ]
        params: list[Any] = [query, query]
        _append_type_filter(where, params, types)

        sql = f"""
            SELECT m.*
            FROM memories AS m
            WHERE {' AND '.join(where)}
            ORDER BY m.id ASC
            LIMIT ?
        """
        params.append(limit)

        with self.db.connection() as conn:
            rows = conn.execute(sql, params).fetchall()
        return [_memory_from_row(row) for row in rows]

    def fts_candidates(
        self,
        match_query: str,
        *,
        types: tuple[str, ...] = (),
        limit: int = 50,
    ) -> list[tuple[Memory, float]]:
        where = ["memory_fts MATCH ?", "m.deleted_at IS NULL"]
        params: list[Any] = [match_query]
        _append_type_filter(where, params, types)

        sql = f"""
            SELECT
                m.*,
                bm25(memory_fts) AS raw_bm25
            FROM memory_fts
            JOIN memories AS m ON m.id = memory_fts.memory_id
            WHERE {' AND '.join(where)}
            ORDER BY raw_bm25 ASC, m.id ASC
            LIMIT ?
        """
        params.append(limit)

        with self.db.connection() as conn:
            try:
                rows = conn.execute(sql, params).fetchall()
            except sqlite3.OperationalError as exc:
                raise ValueError(
                    f"Invalid FTS query generated by MemBus: {match_query!r}"
                ) from exc

        return [(_memory_from_row(row), float(row["raw_bm25"])) for row in rows]

    def alias_map(self, tokens: Iterable[str]) -> dict[str, set[str]]:
        normalized = tuple(dict.fromkeys(t.casefold() for t in tokens if t))
        if not normalized:
            return {}

        placeholders = ",".join("?" for _ in normalized)
        sql = f"""
            SELECT alias, canonical
            FROM aliases
            WHERE alias IN ({placeholders})
        """
        result: dict[str, set[str]] = {token: set() for token in normalized}

        with self.db.connection() as conn:
            for row in conn.execute(sql, normalized):
                result[str(row["alias"]).casefold()].add(
                    str(row["canonical"]).casefold()
                )

        return result

    def put_alias(self, alias: str, canonical: str) -> None:
        with self.db.transaction() as conn:
            conn.execute(
                """
                INSERT INTO aliases(alias, canonical)
                VALUES (?, ?)
                ON CONFLICT(alias) DO UPDATE SET
                    canonical = excluded.canonical
                """,
                (alias.casefold(), canonical.casefold()),
            )


def _append_type_filter(
    where: list[str],
    params: list[Any],
    types: tuple[str, ...],
) -> None:
    if not types:
        return
    placeholders = ",".join("?" for _ in types)
    where.append(f"m.memory_type IN ({placeholders})")
    params.extend(types)


def _memory_params(memory: Memory) -> dict[str, Any]:
    return {column: getattr(memory, column) for column in _MEMORY_COLUMNS}


def _memory_from_row(row: sqlite3.Row) -> Memory:
    return Memory(**{column: row[column] for column in _MEMORY_COLUMNS})
